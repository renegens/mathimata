#!/usr/bin/env python3
"""Fidelity check: every visible text fragment of the old student/teacher pages (and the teacher guide)
must appear, in order, in the new Markdown (frontmatter + body).  Exit code 1 on any failure.

Whitelist (page chrome that the Astro layout supplies), applied ONLY to text inside <nav>,
inside print buttons (button[data-print] / button#print / onclick=window.print) and inside #progress:
"""
import re, sys
from html.parser import HTMLParser
from pathlib import Path
import yaml

SRC = Path('/home/rgg/Work/teaching/lesson-server/public')
SITE = Path(__file__).resolve().parents[1]

NAV_WHITELIST = {'Για μαθητές', 'Για εκπαιδευτές', 'Μαθήματα ενηλίκων', 'Οδηγός 20 ωρών', 'Όλα τα μαθήματα',
                 '← Προηγούμενο μάθημα', 'Επόμενο μάθημα →'}
BUTTON_WHITELIST = {'Εκτύπωση', 'Εκτύπωση σημειώσεων', 'Εκτύπωση προγράμματος'}
PROGRESS_WHITELIST = {'Ολοκληρώθηκαν 0 από 6'}   # lesson 1: placeholder text generated by script
GOAL_PREFIX = 'Στόχος: '   # student header: layout supplies the label, goal field holds the rest

def ws(s): return re.sub(r'\s+', ' ', s).strip()

class Extract(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack, self.items = [], []   # items: (text, kind)
    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        for k in ('placeholder', 'aria-label', 'data-answer'):
            if a.get(k) and not (k == 'aria-label' and tag in ('nav', 'section')):  # landmark labels are chrome
                self.items.append((ws(a[k]), 'attr:' + k))
        if tag in ('meta', 'link', 'input', 'br', 'img'): return
        kind = None
        if tag == 'nav': kind = 'nav'
        elif tag == 'button' and ('data-print' in a or a.get('id') == 'print' or 'window.print' in a.get('onclick', '')): kind = 'button'
        elif a.get('id') == 'progress': kind = 'progress'
        self.stack.append((tag, kind))
    def handle_endtag(self, tag):
        for i in range(len(self.stack) - 1, -1, -1):
            if self.stack[i][0] == tag:
                del self.stack[i:]; return
    def handle_data(self, d):
        if any(t in ('script', 'style', 'title', 'head') for t, _ in self.stack): return
        t = ws(d)
        if not t: return
        kinds = [k for _, k in self.stack if k]
        self.items.append((t, kinds[-1] if kinds else None))

def fragments(path, student):
    p = Extract(); p.feed(path.read_text(encoding='utf-8'))
    out, skipped = [], []
    for t, kind in p.items:
        if kind == 'nav' and t in NAV_WHITELIST: skipped.append(t); continue
        if kind == 'button' and t in BUTTON_WHITELIST: skipped.append(t); continue
        if kind == 'progress' and t in PROGRESS_WHITELIST: skipped.append(t); continue
        if student and t.startswith(GOAL_PREFIX): t = t[len(GOAL_PREFIX):]
        out.append(t)
    return out, skipped

def load(md):
    text = md.read_text(encoding='utf-8')
    m = re.match(r'---\n(.*?)\n---\n(.*)', text, re.S)
    return yaml.safe_load(m.group(1)), m.group(2)

def ordered_missing(frags, hay):
    hay = ws(hay); pos = 0; missing = []
    for f in frags:
        i = hay.find(f, pos)
        if i < 0:
            j = hay.find(f)
            missing.append(f + ('   [present but out of order]' if j >= 0 else ''))
        else: pos = i + len(f)
    return missing

def main():
    fails = 0; skipped_all = {}
    for folder in sorted(SRC.glob('adult-lesson-*')):
        md = SITE / 'src/content/adults' / (folder.name.replace('adult-lesson-', '') + '.md')
        errs = []
        if not md.exists(): errs.append('missing ' + str(md))
        else:
            fm, body = load(md)
            if fm['slug'] != folder.name: errs.append('slug mismatch')
            sf, s1 = fragments(folder / 'index.html', True)
            tf, s2 = fragments(folder / 'teacher-notes.html', False)
            for s in s1 + s2: skipped_all[s] = skipped_all.get(s, 0) + 1
            shay = ' '.join([fm['tag'], fm['title'], fm['goal'], fm['intro'], body, fm.get('next_label') or ''])
            thay = ' '.join([fm['teacher_tag'], fm['teacher_title'], fm['teacher_goal'], fm['teacher']])
            # next_label (lesson 1) sits in the nav at the very end of the source page
            errs += ['student: ' + m for m in ordered_missing(sf, shay)]
            errs += ['teacher: ' + m for m in ordered_missing(tf, thay)]
        print(f'{"PASS" if not errs else "FAIL"}  {folder.name}')
        for e in errs: print('      missing:', e)
        fails += bool(errs)
    guide = SITE / 'src/content/adults-guide/teacher-guide.md'
    errs = []
    if not guide.exists(): errs.append('missing guide')
    else:
        fm, body = load(guide)
        gf, s3 = fragments(SRC / 'adults/teacher-guide.html', False)
        for s in s3: skipped_all[s] = skipped_all.get(s, 0) + 1
        # md table cells hold the same text; compare against body with markdown link syntax removed
        plain = re.sub(r'\]\([^)]*\)', ']', body).replace('[', '').replace(']', '')
        errs += ordered_missing(gf, ' '.join([fm['tag'], fm['title'], fm['intro'], plain]))
    print(f'{"PASS" if not errs else "FAIL"}  teacher-guide')
    for e in errs: print('      missing:', e)
    fails += bool(errs)
    print('\nWhitelisted chrome (nav/print/progress text only; counts across all pages):')
    for k, v in sorted(skipped_all.items()): print(f'   {v:3d} x {k}')
    print('\n%s' % ('ALL PASS' if not fails else f'{fails} FAILED'))
    sys.exit(1 if fails else 0)

if __name__ == '__main__':
    main()
